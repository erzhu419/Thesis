def replace_paragraph(xml, paragraph, prose):
    paragraph_id = paragraph.get(W14 + "paraId")
    pattern = r'<w:p\b[^>]*w14:paraId="' + paragraph_id + r'"[^>]*>.*?</w:p>'
    matches = list(re.finditer(pattern, xml, re.S))
    assert len(matches) == 1
    match = matches[0]
    new = revise(match.group(0), paragraph, prose)
    return xml[:match.start()] + new + xml[match.end():]


def main():
    assert not BACKUP.exists(), "Keep the existing backup; do not rerun the initial edit."
    with ZipFile(DOCUMENT) as source:
        original = source.read("word/document.xml").decode("utf-8")
        body = ET.fromstring(original).find(W + "body")
        assert "".join(body[1076].itertext()) == "4.4 仿真实验与结果分析"
        assert "".join(body[1215].itertext()) == "4.5 本章小结"
        updated = original
        for index, prose in REVISIONS.items():
            updated = replace_paragraph(updated, body[index], prose)
        for index, text in CAPTIONS.items():
            nodes, groups, _ = prose_groups(body[index])
            prose = tuple("".join(nodes[j].text or "" for j in g) for g in groups)
            assert len(prose) == 1
            assert prose[0].split()[0] == text.split()[0]
            updated = replace_paragraph(updated, body[index], (text,))
        for index, texts in TABLE_TEXT.items():
            paragraphs = list(body[index].iter(W + "p"))
            for position, text in texts.items():
                updated = replace_paragraph(updated, paragraphs[position], (text,))

        mask = lambda xml: re.sub(r"(<w:t(?:\s[^>]*)?>).*?(</w:t>)", r"\1\2", xml, flags=re.S)
        assert mask(original) == mask(updated), "Non-text XML changed."
        final_body = ET.fromstring(updated).find(W + "body")
        assert len(body) == len(final_body)
        changed = [i for i, (a, b) in enumerate(zip(body, final_body)) if ET.tostring(a) != ET.tostring(b)]
        assert set(changed) == set(REVISIONS) | set(CAPTIONS) | set(TABLE_TEXT), changed
        assert min(changed) > 1076 and max(changed) < 1215
        protected_count = 0
        for index in changed:
            for tag in (M + "oMath", W + "hyperlink", W + "instrText", W + "fldChar", W + "pPr"):
                assert [ET.tostring(n) for n in body[index].iter(tag)] == [ET.tostring(n) for n in final_body[index].iter(tag)], (index, tag)
            for old, new in zip(body[index].iter(W + "p"), final_body[index].iter(W + "p")):
                old_nodes, _, protected = prose_groups(old)
                new_nodes = list(new.iter(W + "t"))
                assert all(ET.tostring(old_nodes[j]) == ET.tostring(new_nodes[j]) for j in protected), index
                protected_count += len(protected)
        for index, positions in TABLE_TEXT.items():
            before = list(body[index].iter(W + "p"))
            after = list(final_body[index].iter(W + "p"))
            assert len(before) == len(after)
            for j, (a, b) in enumerate(zip(before, after)):
                if j not in positions:
                    assert ET.tostring(a) == ET.tostring(b), (index, j)
        copy2(DOCUMENT, BACKUP)
        temporary = DOCUMENT.with_suffix(".section-edit.docx")
        with ZipFile(temporary, "w") as target:
            for item in source.infolist():
                data = updated.encode("utf-8") if item.filename == "word/document.xml" else source.read(item.filename)
                target.writestr(item, data)
    temporary.replace(DOCUMENT)
    with ZipFile(BACKUP) as before, ZipFile(DOCUMENT) as after:
        assert before.namelist() == after.namelist()
        assert [n for n in before.namelist() if before.read(n) != after.read(n)] == ["word/document.xml"]
    print({"paragraphs": len(REVISIONS), "captions": len(CAPTIONS),
           "table_texts": sum(len(v) for v in TABLE_TEXT.values()),
           "changed_blocks": changed, "protected_text_nodes": protected_count,
           "backup": str(BACKUP), "output": str(DOCUMENT)})


