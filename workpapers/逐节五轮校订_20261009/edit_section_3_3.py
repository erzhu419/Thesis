def paragraph_pattern(paragraph):
    return r'<w:p\b[^>]*w14:paraId="' + paragraph.get(W14 + "paraId") + r'"[^>]*>.*?</w:p>'


def repair_raised_prose(raw, paragraph):
    run = paragraph[-1]
    assert run.tag == W + "r"
    assert (run.find(W + "t").text or "").startswith("，用多个价值网络")
    alignment = run.find(W + "rPr/" + W + "vertAlign")
    assert alignment is not None and alignment.get(W + "val") == "superscript"
    last_run = list(re.finditer(r"<w:r\b[^>]*>.*?</w:r>", raw, re.S))[-1]
    revised_run, count = re.subn(r'<w:vertAlign\b[^>]*w:val="superscript"[^>]*/>', "", last_run.group(0))
    assert count == 1
    return raw[:last_run.start()] + revised_run + raw[last_run.end():]


def main():
    with ZipFile(DOCUMENT) as source:
        original = source.read("word/document.xml").decode("utf-8")
        body = ET.fromstring(original).find(W + "body")
        assert "".join(body[736].itertext()) == "3.3 求解方法"
        assert "".join(body[811].itertext()) == "3.4 仿真实验与结果分析"
        updated = original
        start_match = re.search(paragraph_pattern(body[737]), updated, re.S)
        raised_fixed = repair_raised_prose(start_match.group(0), body[737])
        format_expected = updated[:start_match.start()] + raised_fixed + updated[start_match.end():]
        updated = format_expected
        formatted_body = ET.fromstring(format_expected).find(W + "body")
        for index, prose in REVISIONS.items():
            assert 737 <= index <= 810
            matches = list(re.finditer(paragraph_pattern(body[index]), updated, re.S))
            assert len(matches) == 1
            match = matches[0]
            paragraph = formatted_body[index]
            revised = revise(match.group(0), paragraph, prose)
            updated = updated[:match.start()] + revised + updated[match.end():]

        mask = lambda raw: re.sub(r"(<w:t(?:\s[^>]*)?>).*?(</w:t>)", r"\1\2", raw, flags=re.S)
        assert mask(format_expected) == mask(updated), "Unexpected non-text XML change."
        new_body = ET.fromstring(updated).find(W + "body")
        assert len(body) == len(new_body)
        changed = [i for i, (a, b) in enumerate(zip(body, new_body)) if ET.tostring(a) != ET.tostring(b)]
        assert changed == list(REVISIONS), changed
        if not BACKUP.exists():
            copy2(DOCUMENT, BACKUP)
        with ZipFile(BACKUP) as backup:
            assert backup.read("word/document.xml").decode("utf-8") == original
        temporary = DOCUMENT.with_suffix(".section-edit.docx")
        with ZipFile(temporary, "w") as target:
            for item in source.infolist():
                data = updated.encode("utf-8") if item.filename == "word/document.xml" else source.read(item.filename)
                target.writestr(item, data)
    temporary.replace(DOCUMENT)
    with ZipFile(BACKUP) as before, ZipFile(DOCUMENT) as after:
        assert before.namelist() == after.namelist()
        parts = [name for name in before.namelist() if before.read(name) != after.read(name)]
        assert parts == ["word/document.xml"], parts
    print({"changed_blocks": changed, "paragraph_count": len(changed), "changed_parts": parts,
           "format_repair": "B737 ordinary prose superscript removed; citation superscripts unchanged",
           "backup": str(BACKUP)})


if __name__ == "__main__":
    main()
