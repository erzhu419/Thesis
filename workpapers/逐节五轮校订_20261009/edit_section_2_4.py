def field_results(block):
    results, current, separated = [], [], False
    for node in block.iter():
        if node.tag == W + "fldChar":
            kind = node.get(W + "fldCharType")
            if kind == "separate":
                separated, current = True, []
            elif kind == "end" and separated:
                results.append(tuple(current))
                separated = False
        elif separated and node.tag == W + "t":
            current.append(node.text)
    return results


