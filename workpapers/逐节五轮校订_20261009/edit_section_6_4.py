def replace_terms(text):
    for old, new in TERMS:
        text = text.replace(old, new)
    return text


def main():
    assert not BACKUP.exists(), "Keep the pre-edit backup."
    with ZipFile(DOCUMENT) as source:
        original = source.read("word/document.xml").decode("utf-8")
        body = ET.fromstring(original).find(W + "body")
        assert "".join(body[1696].itertext()) == "6.4 仿真实验与结果分析"
        assert "".join(body[1916].itertext()) == "6.5 本章小结"
        updated = original
        for index, prose in REVISIONS.items():
            assert body[index].tag == W + "p"
            updated = replace_paragraph(updated, body[index], prose)

        # Keep caption number bookmarks and equation/table structure in place.
        parts = list(re.finditer(r"<w:p\b[^>]*>.*?</w:p>", updated, re.S))
        ids = {p.get(W14 + "paraId") for n in body[1697:1916] for p in n.iter(W + "p")}
        for match in reversed(parts):
            para_id = re.search(r'w14:paraId="([^"]+)"', match.group(0))
            if para_id is None or para_id.group(1) not in ids:
                continue
            node = next(p for n in body[1697:1916] for p in n.iter(W + "p") if p.get(W14 + "paraId") == para_id.group(1))
            style = node.find(W + "pPr/" + W + "pStyle")
            if style is not None and style.get(W + "val") in ("h1", "h2", "h3", "h4"):
                continue
            raw = match.group(0)
            _, _, protected = prose_groups(node)
            position = -1

            def change_text(m):
                nonlocal position
                position += 1
                if position in protected:
                    return m.group(0)
                value = replace_terms(unescape(m.group(2)))
                return m.group(1) + escape(value, quote=False) + m.group(3)

            revised = re.sub(r"(<w:t(?:\s[^>]*)?>)(.*?)(</w:t>)", change_text, raw, flags=re.S)
            updated = updated[:match.start()] + revised + updated[match.end():]

        mask = lambda xml: re.sub(r"(<w:t(?:\s[^>]*)?>).*?(</w:t>)", r"\1\2", xml, flags=re.S)
        assert mask(original) == mask(updated), "Non-text XML changed."
        final_body = ET.fromstring(updated).find(W + "body")
        assert len(body) == len(final_body)
        changed = [i for i, (a, b) in enumerate(zip(body, final_body)) if ET.tostring(a) != ET.tostring(b)]
        assert min(changed) > 1696 and max(changed) < 1916
        assert all(ET.tostring(m) == ET.tostring(n) for m, n in zip(body.iter(M + "oMath"), final_body.iter(M + "oMath")))
        assert len(list(body.iter(M + "oMath"))) == len(list(final_body.iter(M + "oMath")))
        protected_count = 0
        for index in changed:
            for before, after in zip(body[index].iter(W + "p"), final_body[index].iter(W + "p")):
                nodes, _, protected = prose_groups(before)
                final_nodes = list(after.iter(W + "t"))
                assert all(ET.tostring(nodes[j]) == ET.tostring(final_nodes[j]) for j in protected), index
                protected_count += len(protected)
                style = before.find(W + "pPr/" + W + "pStyle")
                if style is not None and style.get(W + "val") in ("h1", "h2", "h3", "h4"):
                    assert ET.tostring(before) == ET.tostring(after), index
        copy2(DOCUMENT, BACKUP)
        temporary = DOCUMENT.with_suffix(".section-edit.docx")
        with ZipFile(temporary, "w") as target:
            for item in source.infolist():
                target.writestr(item, updated.encode("utf-8") if item.filename == "word/document.xml" else source.read(item.filename))
    temporary.replace(DOCUMENT)
    with ZipFile(BACKUP) as before, ZipFile(DOCUMENT) as after:
        assert before.namelist() == after.namelist()
        assert [n for n in before.namelist() if before.read(n) != after.read(n)] == ["word/document.xml"]
    print({"changed_blocks": changed, "block_count": len(changed), "protected_text_nodes": protected_count, "non_text_xml_preserved": True, "backup": str(BACKUP)})


if __name__ == "__main__":
    main()
