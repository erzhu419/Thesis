def prose_groups(paragraph):
    nodes = list(paragraph.iter(W + "t"))
    positions = {id(node): i for i, node in enumerate(nodes)}
    groups, current, protected = [], [], set()
    field_depth = 0

    def finish_group():
        if current:
            groups.append(current[:])
            current.clear()

    for child in paragraph:
        fields = list(child.iter(W + "fldChar"))
        if fields or field_depth:
            finish_group()
            protected.update(positions[id(node)] for node in child.iter(W + "t"))
            for field in fields:
                kind = field.get(W + "fldCharType")
                if kind == "begin":
                    field_depth += 1
                elif kind == "end":
                    field_depth -= 1
            continue
        if child.tag == W + "r" and child.find(W + "rPr/" + W + "vertAlign") is None:
            current.extend(positions[id(node)] for node in child.iter(W + "t"))
        elif child.tag in (W + "hyperlink", W + "fldSimple", M + "oMath") or child.tag == W + "r":
            finish_group()
            protected.update(positions[id(node)] for node in child.iter(W + "t"))
    finish_group()
    assert field_depth == 0
    return nodes, groups, protected


def revise(raw, paragraph, prose):
    nodes, groups, protected = prose_groups(paragraph)
    assert len(groups) == len(prose), (len(groups), len(prose))
    replacements = {}
    for indices, text in zip(groups, prose):
        replacements[indices[0]] = text
        replacements.update((index, "") for index in indices[1:])
    assert not (protected & replacements.keys())
    position = -1

    def replace(match):
        nonlocal position
        position += 1
        if position not in replacements:
            return match.group(0)
        return match.group(1) + escape(replacements[position], quote=False) + match.group(3)

    result = re.sub(r"(<w:t(?:\s[^>]*)?>)(.*?)(</w:t>)", replace, raw, flags=re.S)
    assert position + 1 == len(nodes)
    text_pattern = r"(<w:t(?:\s[^>]*)?>)(.*?)(</w:t>)"
    initial_nodes = list(re.finditer(text_pattern, raw, flags=re.S))
    revised_nodes = list(re.finditer(text_pattern, result, flags=re.S))
    assert all(initial_nodes[index].group(0) == revised_nodes[index].group(0) for index in protected)
    return result


def main():
    with ZipFile(DOCUMENT) as source:
        original = source.read("word/document.xml").decode("utf-8")
        body = ET.fromstring(original).find(W + "body")
        assert "".join(body[647].itertext()) == "3.2 模型构建"
        assert "".join(body[736].itertext()) == "3.3 求解方法"
        updated = original
        for index, prose in REVISIONS.items():
            paragraph_id = body[index].get(W14 + "paraId")
            pattern = r'<w:p\b[^>]*w14:paraId="' + paragraph_id + r'"[^>]*>.*?</w:p>'
            matches = list(re.finditer(pattern, updated, flags=re.S))
            assert len(matches) == 1
            match = matches[0]
            revised = revise(match.group(0), body[index], prose)
            updated = updated[:match.start()] + revised + updated[match.end():]

        mask = lambda raw: re.sub(r"(<w:t(?:\s[^>]*)?>).*?(</w:t>)", r"\1\2", raw, flags=re.S)
        assert mask(original) == mask(updated), "Non-text XML changed."
        new_body = ET.fromstring(updated).find(W + "body")
        assert len(body) == len(new_body)
        changed = [i for i, (a, b) in enumerate(zip(body, new_body)) if ET.tostring(a) != ET.tostring(b)]
        assert set(changed).issubset(REVISIONS), changed
        if not BACKUP.exists():
            copy2(DOCUMENT, BACKUP)
        temporary = DOCUMENT.with_suffix(".section-edit.docx")
        with ZipFile(temporary, "w") as target:
            for item in source.infolist():
                data = updated.encode("utf-8") if item.filename == "word/document.xml" else source.read(item.filename)
                target.writestr(item, data)
    temporary.replace(DOCUMENT)
    with ZipFile(BACKUP) as before, ZipFile(DOCUMENT) as after:
        assert before.namelist() == after.namelist()
        changed_parts = [name for name in before.namelist() if before.read(name) != after.read(name)]
        assert changed_parts == ["word/document.xml"], changed_parts
        initial = before.read("word/document.xml").decode("utf-8")
        assert mask(initial) == mask(updated)
        initial_body = ET.fromstring(initial).find(W + "body")
        final_changed = [i for i, (a, b) in enumerate(zip(initial_body, new_body)) if ET.tostring(a) != ET.tostring(b)]
        assert final_changed == list(REVISIONS), final_changed
    print({"changed_blocks": final_changed, "paragraph_count": len(final_changed), "changed_parts": changed_parts, "backup": str(BACKUP)})


